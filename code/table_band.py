# -*- coding: utf-8 -*-
r"""Emit results/tables/tab_band.tex from the band experiment.

Generated rather than hand-written, for the reason the other tables are: a table
typed out of a log drifts from the log the first time the study is re-run, and
nothing catches it.

    python code/table_band.py
"""
from __future__ import annotations

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "results", "bearings")
OUT = os.path.join(HERE, "..", "results", "tables", "tab_band.tex")

test = json.load(io.open(os.path.join(RES, "bandtest.json"), encoding="utf-8"))
sig = json.load(io.open(os.path.join(RES, "bandsig.json"), encoding="utf-8"))
rep = json.load(io.open(os.path.join(RES, "bandsig_rep.json"), encoding="utf-8"))
rept = json.load(io.open(os.path.join(RES, "bandtest_rep.json"), encoding="utf-8"))
shared = len({r["unit"] for r in test["rows"]} & {r["unit"] for r in rept["rows"]})
n_units = len({r["unit"] for r in rept["rows"]})

ORDER = ["0.40-0.55", "0.55-0.70", "0.70-0.80", "0.80-0.90", "0.90-1.01"]
LABEL = {"0.40-0.55": "$40$--$55$", "0.55-0.70": "$55$--$70$",
         "0.70-0.80": "$70$--$80$", "0.80-0.90": "$80$--$90$",
         "0.90-1.01": "$90$--$100$"}

rows = []
for k in ORDER:
    b = test["per_bin"].get(k)
    if not b:
        continue
    band = r"\;$\dagger$" if k in ("0.70-0.80", "0.80-0.90") else ""
    rows.append(f"{LABEL[k]}{band} & {b['units']} & {b['predictions']} & "
                f"{b['median_abs_pct_err']:.1f} & {b['coverage']:.2f}\\\\")

lo, hi = sig["bootstrap_ci"]
p = sig["permutation_p"]
scan = sig["scan"]
best = max(scan, key=lambda c: scan[c])

tex = r"""%  generated by code/table_band.py -- do not edit
\begin{table}[htbp]
\centering
\caption{Path-model error on C-MAPSS units sampled across detected onset; $\dagger$, inside
the $70$--$90\,\%$ band.}
\label{tab:band}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}lrrrr@{}}
\toprule
detected onset (\% of life) & units & predictions
  & median $|$error$|$ (\%) & coverage\\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}

\vspace{4pt}
\begin{minipage}{0.95\linewidth}\footnotesize
The gap across the threshold is
""" + f"{sig['observed_diff']:.0f}" + r""" points
 over """ + f"{sig['n_units_below']}" + r""" units below and """ + \
f"{sig['n_units_above']}" + r""" above; \Cref{sec:band} gives the interval, the
permutation test, the scan over candidate thresholds and the replication.
\end{minipage}
\end{table}
"""

io.open(OUT, "w", encoding="utf-8", newline="").write(tex)
print(f"  wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}")
