def _km_panel(L):
    """Panel (b): the empirical onset distribution of every archive.

    Each record is followed to failure, so the Kaplan--Meier estimate of the
    onset distribution, with undetected records censored at the end of life, is
    the plain cumulative share of records with an onset at or before u.  The
    censored median of Algorithm 3 is where a curve first reaches one half; a
    curve that ends below one half has no median ("not reached").
    """
    import study_p3_review as R
    rec = R._onset_records()
    pre = json.load(io.open(os.path.join(RES, "bearings", "p3_prereg.json"), encoding="utf-8"))
    rec["XJTU Li-ion"] = [r["onset_frac"] for r in pre["battery"]["records"] if "load_error" not in r]
    rec["N-CMAPSS"] = [r["onset_frac"] for r in pre["ncmapss"]["records"]]
    cens = json.load(io.open(os.path.join(RES, "bearings", "p3_review.json"), encoding="utf-8"))["cens"]
    cmed = {k: v["censored_median_pct"] for k, v in cens.items()}
    cmed["XJTU Li-ion"] = pre["battery"]["censored_median_pct"]
    cmed["N-CMAPSS"] = pre["ncmapss"]["censored_median_pct"]
    show = [  # key, legend, style
        ("C-MAPSS FD001", r"C-MAPSS${}\times4$", "black!32, line width=0.5pt"),
        ("C-MAPSS FD003", None, "black!32, line width=0.5pt"),
        ("C-MAPSS FD002+regime", None, "black!32, line width=0.5pt"),
        ("C-MAPSS FD004+regime", None, "black!32, line width=0.5pt"),
        ("NASA cells", "NASA cells", "pGreen, line width=0.8pt"),
        ("XJTU-SY", "XJTU-SY", "pBlue, line width=1.1pt"),
        ("PRONOSTIA", "PRONOSTIA", "pVerm, line width=1.1pt"),
        ("Backblaze drives", "disk drives", "pOrange, line width=1.1pt"),
        ("XJTU Li-ion", r"XJTU cells$^\ddagger$", "pPink, line width=0.9pt, densely dashed"),
        ("N-CMAPSS", r"N-CMAPSS$^\ddagger$", "pSky, line width=0.9pt, densely dashed"),
    ]
    L += [r"  \begin{axis}[p2axis, name=nb, at={(76mm,0mm)}, width=38mm, height=42mm, clip=false,",
          r"      xmin=0, xmax=1, ymin=0, ymax=1.04, xtick={0,0.25,0.5,0.7,0.9,1},",
          r"      xticklabels={0,0.25,0.5,0.7,0.9,1}, ytick={0,0.25,0.5,0.75,1},",
          r"      xlabel={fraction of life $u$}, ylabel={share with onset by $u$}]",
          r"    \fill[pOrange!16] (0.70,0) rectangle (0.90,1.04);",
          r"    \draw[black!55, densely dotted] (0,0.5) -- (1,0.5);"]
    ends = []                                       # (terminal share, label, colour)
    for key, lab, sty in show:
        f = np.sort([v for v in rec[key] if v is not None])
        n = len(rec[key])
        xs = np.concatenate([[0.0], f, [1.0]])
        ys = np.concatenate([[0.0], np.arange(1, len(f) + 1) / n, [len(f) / n]])
        L.append(rf"    \addplot[const plot, {sty}] coordinates {{{co(xs, ys, '{:.4f}')}}};")
        m = cmed.get(key)
        col = sty.split(",")[0]
        if m is not None and "black" not in sty:
            L.append(rf"    \fill[{col}] ({m / 100:.4f},0.5) circle (1.15pt);")
        if lab:
            ends.append([len(f) / n, lab, col.replace("black!32", "black!55")])
    #  Direct labels at the right edge, at each curve's terminal share (its
    #  detection rate), pushed apart just enough not to collide; a short leader
    #  joins each label to its curve.
    ends.sort(key=lambda e: -e[0])
    gap = 0.085
    ylab = [e[0] for e in ends]
    for _ in range(200):
        moved = False
        for i in range(1, len(ylab)):
            if ylab[i - 1] - ylab[i] < gap:
                ylab[i] = ylab[i - 1] - gap
                moved = True
        if not moved:
            break
    shift = max(0.0, ylab[0] - 1.10)
    ylab = [y - shift for y in ylab]
    for (y_end, lab, col), yl in zip(ends, ylab):
        L += [rf"    \draw[{col}, line width=0.35pt] (1.0,{y_end:.4f}) -- (1.06,{yl:.4f});",
              rf"    \node[tiny, anchor=west, text={col}] at (1.065,{yl:.4f}) {{{lab}}};"]
    L += [r"  \end{axis}"]
    title(L, "nb", r"\textbf{(b)}~Onset distribution, every archive")


