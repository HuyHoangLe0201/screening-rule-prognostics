def fig_guided():
    alpha, beta, sig = 0.4, 0.05, 0.012
    x_prev, y = 1.0, 1.004
    a_s, b_s = gbs.bs_consistent_params(alpha, beta, 1.0)
    mu_t = beta * (1 + alpha ** 2 / 2)
    var_t = beta ** 2 * alpha ** 2 * (1 + 1.25 * alpha ** 2)
    dx = np.linspace(1e-4, 0.16, 1400)
    f_tr = gbs.bs_pdf(dx, a_s, b_s)
    g_ob = stats.norm.pdf(y - (x_prev + dx), 0.0, sig)
    g_ob = g_ob / np.trapezoid(g_ob, dx)
    post = f_tr * stats.norm.pdf(y - (x_prev + dx), 0.0, sig)
    post /= np.trapezoid(post, dx)
    v_star = 1.0 / (1.0 / var_t + 1.0 / sig ** 2)
    m_star = v_star * (mu_t / var_t + (y - x_prev) / sig ** 2)
    lo = stats.norm.cdf(-m_star / np.sqrt(v_star))
    q_prop = stats.norm.pdf(dx, m_star, np.sqrt(v_star)) / (1 - lo)
