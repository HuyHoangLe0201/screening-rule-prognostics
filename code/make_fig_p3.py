ONS_B = "Bearing1_1"
YLO, YHI = -0.55, 2.15
IN_K0, IN_K1 = 20, 58
IN_YLO, IN_YHI = -0.002, 0.086


def onset_stats(data):
    hi = np.asarray(data[ONS_B]["hi"], float)
    n = len(hi)
    nh = min(40, max(5, n // 10))
    base = float(np.median(hi[:nh]))
    mad = float(np.median(np.abs(hi[:nh] - base)) * 1.4826)
    band = base + 3.0 * max(mad, 1e-9)
    above = hi > band
    frac = np.cumsum(above[::-1])[::-1] / np.maximum(np.arange(n, 0, -1), 1)
    ons = int(ds.first_prediction_time(hi))
    first = int(np.argmax(above))
    run = int(np.argmin(above[first:]))
    return hi, above, dict(n=n, base=base, mad=mad, band=band, ons=ons, first=first, run=run,
                           frac_first=float(frac[first]), frac_ons=float(frac[ons]),
                           deg=100.0 * (n - ons) / n, lo=float(hi.min()), hi_max=float(hi.max()))


