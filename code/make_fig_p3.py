# ── the decomposition of Theorem 1, on two particle clouds ──────────────────
def _ig_pdf(x, mu, lam):
    return np.sqrt(lam / (2 * np.pi * x ** 3)) * np.exp(-lam * (x - mu) ** 2 / (2 * mu ** 2 * x))


def fig_decomp():
    """Particle-wise inverse Gaussian laws of the remaining life and their mixture.

    Illustrative clouds, not fitted ones: six particles with the same
    conditional variance in both panels, so V_al is the same, and means spread
    widely in (a) and narrowly in (b).  rho, V_al and V_ep are computed here from
    the drawn components with the formulas of Theorem 1, and the arrows have
    exactly those half-widths.
    """
    w = np.array([0.10, 0.18, 0.24, 0.22, 0.16, 0.10])
    x = np.linspace(1.0, 175.0, 350)
    cols = ("pSky", "pBlue", "pGreen", "pOrange", "pPink", "pVerm")
    L = [r"%  GENERATED by code/make_fig_p3.py -- do not edit by hand.",
         r"%  Illustrative particle clouds; rho, V_al and V_ep are computed from the",
         r"%  drawn components with the formulas of Theorem 1."] + list(PRE)
    stats_out = {}
    for name, x0, mus, v_target, tag in (
            ("pa", 8, np.array([40., 55., 70., 85., 100., 115.]), None, "a"),
            ("pb", 78, 76.0 + 3.6 * np.arange(-2.5, 3.0), None, "b")):
        m_bar = float(w @ mus)
        v_ep = float(w @ (mus - m_bar) ** 2)
        var_i = 112.0                                  # one conditional variance
        lam = mus ** 3 / var_i
        v_al = float(w @ (mus ** 3 / lam))
        rho = v_ep / (v_ep + v_al)
        stats_out[tag] = (rho, v_ep, v_al)
        comp = [wi * _ig_pdf(x, m, l) for wi, m, l in zip(w, mus, lam)]
        mix = np.sum(comp, axis=0)
        ymax = 1.55 * mix.max()
        L += [rf"  \begin{{axis}}[p2axis, name={name}, at={{({x0}mm,0mm)}}, width=52mm, height=30mm,",
              rf"      xmin=0, xmax=175, ymin=0, ymax={ymax:.5f}, ytick=\empty, xtick=\empty,",
              r"      xlabel={remaining life}, ylabel={density}, clip=false]"]
        for c, col in zip(comp, cols):
            L.append(rf"    \addplot[{col}, line width=0.6pt] coordinates {{{co(x, c)}}};")
        L.append(rf"    \addplot[black, line width=1.1pt] coordinates {{{co(x, mix)}}};")
        for m, col in zip(mus, cols):
            L.append(rf"    \draw[{col}, line width=0.8pt] (axis cs:{m:.1f},0) -- (axis cs:{m:.1f},{0.06 * ymax:.5f});")
        y1, y2, y3 = 0.99 * ymax, 0.84 * ymax, 0.69 * ymax
        s_ep, s_al, s_tot = np.sqrt(v_ep), np.sqrt(v_al), np.sqrt(v_ep + v_al)
        xl = m_bar + max(s_ep, s_al, s_tot) + 4.0          # one label column
        L += [rf"    \draw[pBlue, <->, >={{Stealth[length=1.4mm]}}] (axis cs:{m_bar - s_ep:.2f},{y1:.5f}) -- (axis cs:{m_bar + s_ep:.2f},{y1:.5f});",
              rf"    \node[tiny, text=pBlue, anchor=west] at (axis cs:{xl:.2f},{y1:.5f}) {{$\sqrt{{V_{{\rm ep}}}}$}};",
              rf"    \draw[pGreen!70!black, <->, >={{Stealth[length=1.4mm]}}] (axis cs:{m_bar - s_al:.2f},{y2:.5f}) -- (axis cs:{m_bar + s_al:.2f},{y2:.5f});",
              rf"    \node[tiny, text=pGreen!70!black, anchor=west] at (axis cs:{xl:.2f},{y2:.5f}) {{$\sqrt{{V_{{\rm al}}}}$}};",
              rf"    \draw[black, <->, >={{Stealth[length=1.4mm]}}] (axis cs:{m_bar - s_tot:.2f},{y3:.5f}) -- (axis cs:{m_bar + s_tot:.2f},{y3:.5f});",
              rf"    \node[tiny, anchor=west] at (axis cs:{xl:.2f},{y3:.5f}) {{total}};",
              r"  \end{axis}"]
        txt = ("the asset is poorly known" if tag == "a" else "the process is noisy")
        title(L, name, rf"\textbf{{({tag})}}~$\rho_k={rho:.2f}$: {txt}")
    L += [r"\end{tikzpicture}",
          r"\caption{The decomposition of \Cref{thm:lotv} on two particle clouds: the weighted law"
          rf" of the remaining life given each particle, their mixture, and the two components,"
          rf" with $\rho_k={stats_out['a'][0]:.2f}$ (a) and ${stats_out['b'][0]:.2f}$ (b).}}",
          r"\label{fig:decomp}", r"\end{figure}"]
