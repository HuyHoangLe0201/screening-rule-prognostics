# ── the model as a graph, and the first passage it implies ──────────────────
def _coupled_paths(x0s, alpha, beta, gamma, x_ref, D, n_max, rng):
    """Paris-coupled, grid-consistent BS paths from each x0 until they cross D."""
    out = []
    for x0 in x0s:
        xs = [x0]
        x = x0
        for _ in range(n_max):
            s = (1.0 + max(x, 0.0) / x_ref) ** gamma
            a_s, b_s = gbs.bs_consistent_params(alpha, beta, s)
            x = x + float(gbs.bs_rvs(a_s, b_s, rng=rng))
            xs.append(x)
            if x >= D:
                break
        out.append(np.array(xs))
    return out


def _crossing(path, D):
    """Interpolated crossing instant of a path that ends above D."""
    k = len(path) - 1
    return k - 1 + (D - path[-2]) / (path[-1] - path[-2])


