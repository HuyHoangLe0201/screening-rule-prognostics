# -*- coding: utf-8 -*-
r"""Emit results/tables/tab_rultest.tex: the pre-registered test of whether a
cohort the screen declines predicts worse (PREREG_p3_rul.md).

One row per charging regime of the XJTU cells, with the screen's verdict on
that regime alone, then the two pooled cohorts of the protocol.  The gradient
boosting columns come from study_p3_gbr.py, run after the test was scored.
Every cell is read from results/bearings/p3_rul.json, p3_review.json and
p3_gbr.json.

    python code/table_rultest.py
"""
from __future__ import annotations

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BE = os.path.join(HERE, "..", "results", "bearings")
OUT = os.path.join(HERE, "..", "results", "tables", "tab_rultest.tex")

T = json.load(io.open(os.path.join(BE, "p3_rul.json"), encoding="utf-8"))
V = json.load(io.open(os.path.join(BE, "p3_review.json"), encoding="utf-8"))["regime"]
G = json.load(io.open(os.path.join(BE, "p3_gbr.json"), encoding="utf-8"))
NAME = {"2C": "2C charge", "3C": "3C charge", "R2.5": "R2.5", "R3": "R3",
        "RW": "random walk", "Sim_satellite": "satellite profile"}


def gb(g):
    if not g or not g.get("units"):
        return "-- & --"
    return f"{g['medape_gb']:.1f} & {g['coverage_gb']:.2f}"


def cells(c, g=None):
    return (f"{c['cells']} & {c['predictions']} & {c['medape_path']:.1f} & "
            f"{c['coverage_path']:.2f} & {c['medape_lt']:.1f} & {c['coverage_lt']:.2f} & {gb(g)}")


body = []
for b, c in sorted(T["by_regime"].items()):
    v = V[b]
    body.append(f"{NAME[v['regime']]} & {v['verdict']} & {cells(c, G.get(b))}\\\\")
body.append(r"\midrule")
body.append(f"declined cohort & 3C & {cells(T['declined'], G['cells_declined'])}\\\\")
body.append(f"passed cohort & four regimes & {cells(T['passed'], G['cells_passed'])}\\\\")
d1, d2 = T["diff_medape_path"], T["diff_coverage_path"]
tex = r"""%  generated by code/table_rultest.py -- do not edit
\begin{table}[htbp]
\centering
\caption{The pre-registered test of prediction quality on the XJTU cells, by
charging regime and by cohort.}
\label{tab:rultest}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}llrrrrrrrr@{}}
\toprule
& & & & \multicolumn{2}{c}{path model} & \multicolumn{2}{c}{life table} & \multicolumn{2}{c}{boosting}\\
\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}
regime & verdict & cells & points & MedAPE & coverage & MedAPE & coverage & MedAPE & coverage\\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}

\vspace{4pt}
\begin{minipage}{0.95\linewidth}\footnotesize
Predictions at $50$, $70$ and $85\,\%$ of each cell's life; MedAPE is the
median absolute percentage error, coverage that of the nominal $95\,\%$
interval. Declined minus passed, the path model's MedAPE differs by
""" + f"${d1['obs']:+.1f}$ $[{d1['ci'][0]:+.1f},{d1['ci'][1]:+.1f}]$ and its coverage by " \
    + f"${d2['obs']:+.2f}$ $[{d2['ci'][0]:+.2f},{d2['ci'][1]:+.2f}]$" + r""", by a bootstrap
clustered on the cell. Gradient boosting on the indicator was added after the
test was scored. Random-walk cells are undecided and enter neither cohort; five
of them are too short to predict, and too few remain to train boosting.
\end{minipage}
\end{table}
"""
io.open(OUT, "w", encoding="utf-8", newline="").write(tex)
print(f"  wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}")
