# -*- coding: utf-8 -*-
r"""Emit results/tables/tab_altind.tex: the screen on five indicators built the
same way from the same bearing records (study_p3_review.py altind).

    python code/table_altind.py
"""
from __future__ import annotations

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "results", "bearings")
OUT = os.path.join(HERE, "..", "results", "tables", "tab_altind.tex")

A = json.load(io.open(os.path.join(RES, "p3_review.json"), encoding="utf-8"))["altind"]


def fmt(v):
    return "n.r." if v is None else f"{v:.1f}"


def cells(r):
    lo, hi = r["censored_median_ci"]
    return (f"{r['n_detected']}/{r['n']} & {fmt(r['censored_median_pct'])} "
            f"[{fmt(lo)}, {fmt(hi)}] & {r['verdict']}")


body = "\n".join(f"{ind} & {cells(A['pronostia'][ind])} & {cells(A['xjtu'][ind])}\\\\"
                 for ind in A["pronostia"])
tex = r"""%  generated by code/table_altind.py -- do not edit
\begin{table}[htbp]
\centering
\caption{The screen on five indicators of the same bearing records.}
\label{tab:altind}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}l rcl rcl@{}}
\toprule
& \multicolumn{3}{c}{PRONOSTIA} & \multicolumn{3}{c}{XJTU-SY}\\
\cmidrule(lr){2-4}\cmidrule(lr){5-7}
indicator & detected & censored median & verdict & detected & censored median & verdict\\
\midrule
""" + body + r"""
\bottomrule
\end{tabular}
\end{adjustbox}

\vspace{4pt}
\begin{minipage}{0.95\linewidth}\footnotesize
Each indicator combines the horizontal and vertical channels (the Euclidean norm,
or the mean for kurtosis), is causally smoothed with the archive's window, divided
by its healthy-window median and logged, as log RMS is. The detector, its
constants and Algorithm~\ref{alg:screen} are unchanged; brackets are $95\,\%$
percentile bootstrap intervals, in \% of life.
\end{minipage}
\end{table}
"""
io.open(OUT, "w", encoding="utf-8", newline="").write(tex)
print(f"  wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}")
