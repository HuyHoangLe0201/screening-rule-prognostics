# -*- coding: utf-8 -*-
r"""Emit results/tables/tab_fatigue.tex: the pre-registered external test on
strain-controlled fatigue specimens, an asset class that took no part in
building the screen (PREREG_p3_fatigue.md).

One row per strain-ratio cohort, then the pooled cohort: the screen's verdict
with its censored median onset, and the path model, the amplitude-scaled life
table and gradient boosting.  Every cell is read from
results/bearings/p3_fatigue.json.

    python code/table_fatigue.py
"""
from __future__ import annotations

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BE = os.path.join(HERE, "..", "results", "bearings")
OUT = os.path.join(HERE, "..", "results", "tables", "tab_fatigue.tex")

T = json.load(io.open(os.path.join(BE, "p3_fatigue.json"), encoding="utf-8"))


def _pct(x):
    return "n.r." if x is None else f"{x:.1f}"


def row(label, s, v):
    lo, hi = s["ci"]
    pred = (f"{v['medape_path']:.1f} & {v['coverage_path']:.2f} & {v['medape_lt']:.1f} & "
            f"{v['coverage_lt']:.2f} & {v['medape_gb']:.1f} & {v['coverage_gb']:.2f}"
            if v else r"\multicolumn{6}{c}{---}")
    return (f"{label} & {s['n']} & {_pct(s['censored_median_pct'])} $[{_pct(lo)},{_pct(hi)}]$ & "
            f"{s['verdict']} & {pred}\\\\")


cohorts = sorted((c for c in T["screen"] if c != "pooled"), key=float)
body = [row(f"${float(c):g}$", T["screen"][c], T["by_cohort"].get(c)) for c in cohorts
        if T["screen"][c]["verdict"] != "too few"]
body.append(r"\midrule")
body.append(row("pooled", T["screen"]["pooled"], T["pooled"]))
tex = r"""%  generated by code/table_fatigue.py -- do not edit
\begin{table}[htbp]
\centering
\caption{The pre-registered external test on titanium fatigue specimens, by strain ratio.}
\label{tab:fatigue}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}lrllrrrrrr@{}}
\toprule
& & & & \multicolumn{2}{c}{path model} & \multicolumn{2}{c}{scaled life table} & \multicolumn{2}{c}{boosting}\\
\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}
$R_\varepsilon$ & units & median onset, \% & verdict & MedAPE & coverage & MedAPE & coverage & MedAPE & coverage\\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}

\vspace{4pt}
\begin{minipage}{0.95\linewidth}\footnotesize
$R_\varepsilon$ is the strain ratio. The median onset is censored, with its
bootstrap interval (n.r.: not reached); predictions at $50$, $70$ and
$85\,\%$ of each specimen's life.
\end{minipage}
\end{table}
"""
io.open(OUT, "w", encoding="utf-8", newline="").write(tex)
print(f"  wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}")
