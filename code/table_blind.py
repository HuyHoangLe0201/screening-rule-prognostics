# -*- coding: utf-8 -*-
r"""Emit results/tables/tab_blind.tex: the blind pre-registered test on the
N-CMAPSS subsets no earlier analysis opened (PREREG_p3_blind.md).

One row per subset: the screen's verdict with its censored median onset, then
the path model, the life table and gradient boosting (study_p3_gbr.py, run
after the test was scored).  Every cell is read from p3_blind.json and
p3_gbr.json.

    python code/table_blind.py
"""
from __future__ import annotations

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BE = os.path.join(HERE, "..", "results", "bearings")
OUT = os.path.join(HERE, "..", "results", "tables", "tab_blind.tex")

T = json.load(io.open(os.path.join(BE, "p3_blind.json"), encoding="utf-8"))
G = json.load(io.open(os.path.join(BE, "p3_gbr.json"), encoding="utf-8"))["blind_by_cohort"]


def subset(tag):
    return tag.replace("N-CMAPSS_", "").split("-")[0]


body = []
for c, v in sorted(T["by_cohort"].items()):
    lo, hi = v["ci"]
    g = G[c]
    body.append(f"{subset(c)} & {v['units']} & {v['censored_median_pct']:.1f} "
                f"$[{lo:.1f},{hi:.1f}]$ & {v['verdict']} & {v['medape_path']:.1f} & "
                f"{v['coverage_path']:.2f} & {v['medape_lt']:.1f} & {v['coverage_lt']:.2f} & "
                f"{g['medape_gb']:.1f} & {g['coverage_gb']:.2f}\\\\")
b2 = T["B2"]
tex = r"""%  generated by code/table_blind.py -- do not edit
\begin{table}[htbp]
\centering
\caption{The blind pre-registered test on seven N-CMAPSS subsets that no earlier
analysis had opened.}
\label{tab:blind}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}lrllrrrrrr@{}}
\toprule
& & & & \multicolumn{2}{c}{path model} & \multicolumn{2}{c}{life table} & \multicolumn{2}{c}{boosting}\\
\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}
subset & units & median onset, \% & verdict & MedAPE & coverage & MedAPE & coverage & MedAPE & coverage\\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}

\vspace{4pt}
\begin{minipage}{0.95\linewidth}\footnotesize
The median onset is censored, with its bootstrap interval. Across the """ \
    + f"{T['n_units']}" + r""" units, the Spearman correlation between onset and the path model's
error is """ + f"${b2['rho']:.2f}$ $[{b2['ci'][0]:.2f},{b2['ci'][1]:.2f}]$" + r""". Gradient
boosting on the indicator was added after the test was scored. DS08d is
truncated in the archive and could not be opened.
\end{minipage}
\end{table}
"""
io.open(OUT, "w", encoding="utf-8", newline="").write(tex)
print(f"  wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}")
