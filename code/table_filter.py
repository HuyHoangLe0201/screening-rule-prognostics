# -*- coding: utf-8 -*-
r"""Emit results/tables/tab_filter.tex: the pre-registered external test on
filters, an asset class that took no part in building the screen
(PREREG_p3_filter.md).

One row per orifice cohort, then the pooled cohort: the screen's verdict with
its censored median onset, and the path model, the life table and gradient
boosting.  Every cell is read from results/bearings/p3_filter.json.

    python code/table_filter.py
"""
from __future__ import annotations

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BE = os.path.join(HERE, "..", "results", "bearings")
OUT = os.path.join(HERE, "..", "results", "tables", "tab_filter.tex")

T = json.load(io.open(os.path.join(BE, "p3_filter.json"), encoding="utf-8"))


def row(label, s, v):
    lo, hi = s["ci"]
    return (f"{label} & {v['runs']} & {s['censored_median_pct']:.1f} $[{lo:.1f},{hi:.1f}]$ & "
            f"{s['verdict']} & {v['medape_path']:.1f} & {v['coverage_path']:.2f} & "
            f"{v['medape_lt']:.1f} & {v['coverage_lt']:.2f} & {v['medape_gb']:.1f} & "
            f"{v['coverage_gb']:.2f}\\\\")


body = [row(f"{float(c):.1f}\\,\\%", T["screen"][c], v)
        for c, v in sorted(T["by_cohort"].items(), key=lambda kv: -float(kv[0]))]
body.append(r"\midrule")
body.append(row("pooled", T["screen"]["pooled"], T["pooled"]))
tex = r"""%  generated by code/table_filter.py -- do not edit
\begin{table}[htbp]
\centering
\caption{The pre-registered external test on forty filters, by orifice cohort.}
\label{tab:filter}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}lrllrrrrrr@{}}
\toprule
& & & & \multicolumn{2}{c}{path model} & \multicolumn{2}{c}{life table} & \multicolumn{2}{c}{boosting}\\
\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}
orifice & runs & median onset, \% & verdict & MedAPE & coverage & MedAPE & coverage & MedAPE & coverage\\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}

\vspace{4pt}
\begin{minipage}{0.95\linewidth}\footnotesize
The orifice gives the open share of the filtration area. The median onset is
censored, with its bootstrap interval; predictions at $50$, $70$ and $85\,\%$ of
each run's life.
\end{minipage}
\end{table}
"""
io.open(OUT, "w", encoding="utf-8", newline="").write(tex)
print(f"  wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}")
