# -*- coding: utf-8 -*-
r"""Emit results/tables/tab_ladder.tex: coverage as the differences between data
from the model and the benchmarks are added one at a time.

Data from the model raw, then smoothed as each archive's indicator is; the
benchmarks smoothed, then raw, where the independent-noise observation model
holds; then, on the raw indicator at one point per record, the Liu--West filter
against the exact posterior, split by whether the record's onset precedes the
point, counting converged chains only.  Every cell is read from a stored result.

    python code/table_ladder.py
"""
from __future__ import annotations

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BE = os.path.join(HERE, "..", "results", "bearings")
OUT = os.path.join(HERE, "..", "results", "tables", "tab_ladder.tex")

R = json.load(io.open(os.path.join(BE, "p3_review.json"), encoding="utf-8"))
P = json.load(io.open(os.path.join(BE, "results_both.json"), encoding="utf-8"))["tables"]
SMOOTH = {"pronostia": "15", "xjtu": "9"}       # the archives' smoothing windows


def rng_cov(window):
    v = [R["cal"][window][f]["coverage"] for f in R["cal"][window]]
    return f"{min(v):.2f}--{max(v):.2f}"


def count(c):
    return f"{c[0]}/{c[1]}"


ex = R["exact"]["raw"]
rows = [
    ("model", "raw", "Liu--West", r"\multicolumn{2}{c}{" + rng_cov("1") + "}"),
    ("model", "smoothed as the archive", "Liu--West",
     f"{rng_cov(SMOOTH['pronostia'])} & {rng_cov(SMOOTH['xjtu'])}"),
    ("benchmark", "smoothed", "Liu--West",
     f"{P['pronostia/process']['BS']['coverage95']:.2f} & "
     f"{P['xjtu/process']['BS']['coverage95']:.2f}"),
    ("benchmark", "raw", "Liu--West",
     f"{R['sens']['raw_indicator']['pronostia']['coverage95']:.2f} & "
     f"{R['sens']['raw_indicator']['xjtu']['coverage95']:.2f}"),
    ("benchmark, one point per record", "raw", "Liu--West",
     " & ".join(count((round(ex[n]['main']['coverage95'] * ex[n]['main']['n']),
                       ex[n]['main']['n'])) for n in ("pronostia", "xjtu"))),
]
for side, nm in (("before", "onset before the point"), ("after", "onset after the point")):
    cells = []
    for n in ("pronostia", "xjtu"):
        b = ex[n]["by_onset"][side]
        cells.append(count((b["covered_converged"], b["n_converged"])))
    rows.append((f"\\quad {nm}", "raw", "exact, converged", " & ".join(cells)))

body = "\n".join(f"{a} & {b} & {c} & {d}\\\\" for a, b, c, d in rows)
n_unconv = sum(ex[n]["by_onset"][s]["n"] - ex[n]["by_onset"][s]["n_converged"]
               for n in ("pronostia", "xjtu") for s in ("before", "after"))
tex = r"""%  generated by code/table_ladder.py -- do not edit
\begin{table}[htbp]
\centering
\caption{Coverage of the nominal $95\,\%$ interval as the differences between data
from the model and the benchmarks are added one at a time.}
\label{tab:ladder}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}llrcc@{}}
\toprule
data & indicator & inference & PRONOSTIA & XJTU-SY\\
\midrule
""" + body + r"""
\bottomrule
\end{tabular}
\end{adjustbox}

\vspace{4pt}
\begin{minipage}{0.95\linewidth}\footnotesize
Data from the model are smoothed with each archive's window ($15$ and $9$
acquisitions); ranges are over $40$, $60$ and $80\,\%$ of life. The benchmark
rows use every prediction point; the last three, one point per record nearest
$70\,\%$ of life, as counts covered out of points. The exact rows count
converged chains only; """ + f"{n_unconv}" + r""" points whose chains did not
converge are left out (\Cref{sec:ppc}).
\end{minipage}
\end{table}
"""
io.open(OUT, "w", encoding="utf-8", newline="").write(tex)
print(f"  wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}")
