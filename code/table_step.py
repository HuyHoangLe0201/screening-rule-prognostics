# -*- coding: utf-8 -*-
r"""Emit results/tables/tab_step.tex: the pre-registered test of the step across
the threshold on C-MAPSS units never predicted before (PREREG_p3_step.md).

One row per onset bin, then the early and late groups of the protocol.  Every
cell is read from results/bearings/p3_step.json.

    python code/table_step.py
"""
from __future__ import annotations

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BE = os.path.join(HERE, "..", "results", "bearings")
OUT = os.path.join(HERE, "..", "results", "tables", "tab_step.tex")

T = json.load(io.open(os.path.join(BE, "p3_step.json"), encoding="utf-8"))


def row(label, v):
    return (f"{label} & {v['units']} & {v['medape_path']:.1f} & {v['coverage_path']:.2f} & "
            f"{v['medape_lt']:.1f} & {v['coverage_lt']:.2f} & {v['medape_gb']:.1f} & "
            f"{v['coverage_gb']:.2f}\\\\")


body = []
for b, v in T["by_bin"].items():
    lo, hi = (float(x) for x in b.split("-"))
    body.append(row(f"{100 * lo:.0f}--{min(100 * hi, 100):.0f}", v))
body.append(r"\midrule")
body.append(row("early, below 70", T["early"]))
body.append(row("late, 70 or more", T["late"]))
d1, d3 = T["D1"], T["D3"]
tex = r"""%  generated by code/table_step.py -- do not edit
\begin{table}[htbp]
\centering
\caption{The pre-registered test of the step across the threshold, on C-MAPSS
units never predicted before.}
\label{tab:step}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}lrrrrrrr@{}}
\toprule
& & \multicolumn{2}{c}{path model} & \multicolumn{2}{c}{life table} & \multicolumn{2}{c}{boosting}\\
\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}
onset, \% of life & units & MedAPE & coverage & MedAPE & coverage & MedAPE & coverage\\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}

\vspace{4pt}
\begin{minipage}{0.95\linewidth}\footnotesize
Late minus early, the path model's MedAPE differs by """ \
    + f"${d1['diff']:+.1f}$ $[{d1['ci'][0]:+.1f},{d1['ci'][1]:+.1f}]$ and its coverage by " \
    + f"${d3['diff']:+.2f}$ $[{d3['ci'][0]:+.2f},{d3['ci'][1]:+.2f}]$" + r""", by a bootstrap
over units. Gradient boosting on the indicator is the protocol's descriptive
comparator.
\end{minipage}
\end{table}
"""
io.open(OUT, "w", encoding="utf-8", newline="").write(tex)
print(f"  wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}")
