# -*- coding: utf-8 -*-
r"""Emit results/tables/tab_decide.tex: the screen as a decision.

(a) Over the cohorts where both the path model and a life table were scored,
the verdict at each threshold against whether the path model was as accurate
as the life table.  (b) How the verdict depends on cohort size, from
subsamples of five archives.  Read from p3_review.json (parts decisions and
subsample).

    python code/table_decide.py
"""
from __future__ import annotations

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BE = os.path.join(HERE, "..", "results", "bearings")
OUT = os.path.join(HERE, "..", "results", "tables", "tab_decide.tex")

R = json.load(io.open(os.path.join(BE, "p3_review.json"), encoding="utf-8"))
D, S = R["decisions"], R["subsample"]

rows_a = []
for t in ("50", "60", "70", "80", "90"):
    n = D["by_threshold"][t]
    rows_a.append(f"{t} & {n['correct_rejection']} & {n['false_rejection']} & "
                  f"{n['correct_pass']} & {n['false_acceptance']} & {n['undecided']}\\\\")
rows_b = []
for a in ("PRONOSTIA", "XJTU-SY", "XJTU cells 3C", "C-MAPSS FD001", "Backblaze drives"):
    for n in ("5", "10", "15"):
        if n not in S[a]:
            continue
        v = S[a][n]
        rows_b.append(f"{a if n == '5' else ''} & {n} & {v['declines']:.2f} & "
                      f"{v['not declined']:.2f} & {v['undecided']:.2f} & {v['check indicator']:.2f}\\\\")

tex = r"""%  generated by code/table_decide.py -- do not edit
\begin{table}[htbp]
\centering
\caption{The screen as a decision: its verdicts against the path model's
accuracy, and their dependence on cohort size.}
\label{tab:decide}
\footnotesize
\begin{minipage}[t]{0.42\linewidth}\centering
(a) """ + f"{D['n_cohorts']}" + r""" cohorts, """ + f"{D['n_usable']}" + r""" usable\\[2pt]
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}rrrrrr@{}}
\toprule
& \multicolumn{2}{c}{declined} & \multicolumn{2}{c}{passed} & \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}
threshold & right & wrong & right & wrong & undec.\\
\midrule
""" + "\n".join(rows_a) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}
\end{minipage}\hfill
\begin{minipage}[t]{0.56\linewidth}\centering
(b) share of $1000$ subsamples\\[2pt]
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}lrrrrr@{}}
\toprule
archive & $n$ & declines & passes & undec. & check\\
\midrule
""" + "\n".join(rows_b) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}
\end{minipage}

\vspace{4pt}
\begin{minipage}{0.95\linewidth}\footnotesize
(a) A cohort is usable when the path model's median absolute percentage error
is no worse than the life table's; a decline is right on an unusable cohort and
a pass on a usable one. The cohorts are the two bearing archives, five cell
regimes and the seven blind N-CMAPSS subsets. (b) Subsamples of $n$ records
drawn without replacement, each judged at $70\,\%$ with its own bootstrap.
\end{minipage}
\end{table}
"""
io.open(OUT, "w", encoding="utf-8", newline="").write(tex)
print(f"  wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}")
